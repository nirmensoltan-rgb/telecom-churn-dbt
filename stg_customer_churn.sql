-- Rename columns to snake_case, cast types, and make "no service" blanks explicit.
-- The data dictionary says these should be 'No' / 'None' / 0, but the raw table leaves them blank.
select
    {{ adapter.quote('Customer ID') }} as customer_id,
    {{ adapter.quote('Gender') }} as gender,
    cast({{ adapter.quote('Age') }} as integer) as age,
    {{ adapter.quote('Married') }} as married,
    cast({{ adapter.quote('Number of Dependents') }} as integer) as number_of_dependents,
    {{ adapter.quote('City') }} as city,
    lpad(cast({{ adapter.quote('Zip Code') }} as varchar), 5, '0') as zip_code,
    {{ adapter.quote('Latitude') }} as latitude,
    {{ adapter.quote('Longitude') }} as longitude,
    cast({{ adapter.quote('Number of Referrals') }} as integer) as number_of_referrals,
    cast({{ adapter.quote('Tenure in Months') }} as integer) as tenure_months,
    coalesce({{ adapter.quote('Offer') }}, 'None') as offer,
    {{ adapter.quote('Phone Service') }} as phone_service,
    coalesce({{ adapter.quote('Avg Monthly Long Distance Charges') }}, 0) as avg_monthly_long_distance_charges,
    coalesce({{ adapter.quote('Multiple Lines') }}, 'No') as multiple_lines,
    {{ adapter.quote('Internet Service') }} as internet_service,
    coalesce({{ adapter.quote('Internet Type') }}, 'None') as internet_type,
    coalesce({{ adapter.quote('Avg Monthly GB Download') }}, 0) as avg_monthly_gb_download,
    coalesce({{ adapter.quote('Online Security') }}, 'No') as online_security,
    coalesce({{ adapter.quote('Online Backup') }}, 'No') as online_backup,
    coalesce({{ adapter.quote('Device Protection Plan') }}, 'No') as device_protection_plan,
    coalesce({{ adapter.quote('Premium Tech Support') }}, 'No') as premium_tech_support,
    coalesce({{ adapter.quote('Streaming TV') }}, 'No') as streaming_tv,
    coalesce({{ adapter.quote('Streaming Movies') }}, 'No') as streaming_movies,
    coalesce({{ adapter.quote('Streaming Music') }}, 'No') as streaming_music,
    coalesce({{ adapter.quote('Unlimited Data') }}, 'No') as unlimited_data,
    {{ adapter.quote('Contract') }} as contract,
    {{ adapter.quote('Paperless Billing') }} as paperless_billing,
    {{ adapter.quote('Payment Method') }} as payment_method,
    {{ adapter.quote('Monthly Charge') }} as monthly_charge,
    {{ adapter.quote('Total Charges') }} as total_charges,
    {{ adapter.quote('Total Refunds') }} as total_refunds,
    {{ adapter.quote('Total Extra Data Charges') }} as total_extra_data_charges,
    {{ adapter.quote('Total Long Distance Charges') }} as total_long_distance_charges,
    {{ adapter.quote('Total Revenue') }} as total_revenue,
    {{ adapter.quote('Customer Status') }} as customer_status,
    {{ adapter.quote('Churn Category') }} as churn_category,
    {{ adapter.quote('Churn Reason') }} as churn_reason
from {{ source('raw', 'customer_churn') }}